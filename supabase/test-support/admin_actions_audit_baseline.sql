create type public.moderation_action_type as enum('warning','restrict_account','suspend_account','restore_account','pause_listing','remove_listing','dismiss_report');
create table public.moderation_actions(
 id uuid primary key default gen_random_uuid(),
 report_id uuid references public.reports on delete set null,
 admin_id uuid not null references public.profiles on delete restrict,
 action_type public.moderation_action_type not null,
 target_user_id uuid references public.profiles on delete set null,
 target_listing_id uuid references public.listings on delete set null,
 reason text not null,
 starts_at timestamptz not null default now(),
 ends_at timestamptz,
 created_at timestamptz not null default now(),
 constraint moderation_target_present check(target_user_id is not null or target_listing_id is not null or action_type='dismiss_report'));
create index idx_moderation_target_user on public.moderation_actions(target_user_id,created_at desc);
create table public.admin_audit_logs(
 id bigint generated by default as identity primary key,
 admin_id uuid references public.profiles on delete set null,
 action text not null,
 entity_type text not null,
 entity_id uuid,
 metadata jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now());
alter table public.moderation_actions enable row level security;
alter table public.admin_audit_logs enable row level security;
create policy moderation_actions_admin_only on public.moderation_actions for all to authenticated using(public.is_admin());
create policy admin_audit_logs_admin_only on public.admin_audit_logs for all to authenticated using(public.is_admin());
revoke all on public.moderation_actions,public.admin_audit_logs from public,anon,authenticated,service_role;
create function public.apply_moderation_action() returns trigger language plpgsql security definer set search_path=public as $ama$
begin
  if not public.is_admin(new.admin_id) then
    raise exception 'Moderation actions require an admin actor';
  end if;

  case new.action_type
    when 'restrict_account' then
      update public.profiles
      set account_status = 'restricted',
          suspension_reason = new.reason,
          suspended_until = new.ends_at,
          updated_at = now()
      where id = new.target_user_id;

    when 'suspend_account' then
      update public.profiles
      set account_status = 'suspended',
          suspension_reason = new.reason,
          suspended_until = new.ends_at,
          updated_at = now()
      where id = new.target_user_id;

    when 'restore_account' then
      update public.profiles
      set account_status = 'active',
          suspension_reason = null,
          suspended_until = null,
          updated_at = now()
      where id = new.target_user_id;

    when 'pause_listing' then
      update public.listings
      set status = 'paused',
          paused_at = now(),
          updated_at = now()
      where id = new.target_listing_id;

    when 'remove_listing' then
      update public.listings
      set status = 'removed',
          removed_at = now(),
          removal_reason = new.reason,
          updated_at = now()
      where id = new.target_listing_id;

    when 'dismiss_report' then
      update public.reports
      set status = 'dismissed',
          admin_summary = new.reason,
          resolved_at = now(),
          updated_at = now()
      where id = new.report_id;

    else
      null;
  end case;

  insert into public.admin_audit_logs (
    admin_id,
    action,
    entity_type,
    entity_id,
    metadata
  )
  values (
    new.admin_id,
    new.action_type::text,
    case
      when new.target_user_id is not null then 'user'
      when new.target_listing_id is not null then 'listing'
      else 'report'
    end,
    coalesce(new.target_user_id, new.target_listing_id, new.report_id),
    jsonb_build_object('report_id', new.report_id, 'reason', new.reason, 'ends_at', new.ends_at)
  );

  return new;
end;
$ama$;
alter function public.apply_moderation_action() owner to postgres;
create trigger trg_apply_moderation_action after insert on public.moderation_actions for each row execute function apply_moderation_action();
